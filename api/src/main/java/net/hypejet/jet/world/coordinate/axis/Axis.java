package net.hypejet.jet.world.coordinate.axis;

/**
 * An axis of a three-dimensional coordinate system.
 *
 * @since 1.0
 */
public enum Axis {
    /**
     * The {@code X} axis.
     *
     * @since 1.0
     */
    X,
    /**
     * The {@code Y} axis.
     *
     * @since 1.0
     */
    Y,
    /**
     * The {@code Z} axis.
     *
     * @since 1.0
     */
    Z
}