package net.hypejet.jet.world.block.half;

/**
 * A half of a block built from two actual blocks.
 *
 * <p>Contents of this enum depend on Minecraft, however it is safe to keep
 * it an enum, since it is very unlikely to change.</p>
 *
 * @since 1.0
 */
public enum DoubleBlockHalf {
    /**
     * The upper half.
     *
     * @since 1.0
     */
    UPPER,
    /**
     * The lower half.
     *
     * @since 1.0
     */
    LOWER
}