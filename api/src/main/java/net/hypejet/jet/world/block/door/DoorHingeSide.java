package net.hypejet.jet.world.block.door;

/**
 * The side on which a door block has hinges.
 *
 * <p>Contents of this enum depend on Minecraft, however it is safe to keep
 * it an enum, since it is very unlikely to change.</p>
 *
 * @since 1.0
 */
public enum DoorHingeSide {
    /**
     * The left hinge side.
     *
     * @since 1.0
     */
    LEFT,
    /**
     * The right hinge side.
     *
     * @since 1.0
     */
    RIGHT
}