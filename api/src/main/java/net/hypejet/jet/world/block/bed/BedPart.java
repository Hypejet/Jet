package net.hypejet.jet.world.block.bed;

/**
 * The part of a bed block.
 *
 * <p>Contents of this enum depend on Minecraft, however it is safe to keep
 * it an enum, since it is very unlikely to change.</p>
 *
 * @since 1.0
 */
public enum BedPart {
    /**
     * The part of the bed block where player head is put on.
     *
     * @since 1.0
     */
    HEAD,
    /**
     * The part of the bed block where player feet are put on.
     *
     * @since 1.0
     */
    FOOT
}