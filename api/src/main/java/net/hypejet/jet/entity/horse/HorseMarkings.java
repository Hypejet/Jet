package net.hypejet.jet.entity.horse;

/**
 * The type of Minecraft horse markings.
 *
 * @since 1.0
 */
public enum HorseMarkings {
    /**
     * The markings type indicating that a horse entity does not have markings.
     *
     * @since 1.0
     */
    NONE,
    /**
     * The white horse markings.
     *
     * @since 1.0
     */
    WHITE,
    /**
     * The white-field horse markings.
     *
     * @since 1.0
     */
    WHITE_FIELD,
    /**
     * The white-dot horse markings.
     *
     * @since 1.0
     */
    WHITE_DOTS,
    /**
     * The black-dot horse markings.
     *
     * @since 1.0
     */
    BLACK_DOTS
}