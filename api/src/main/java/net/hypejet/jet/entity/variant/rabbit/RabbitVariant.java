package net.hypejet.jet.entity.variant.rabbit;

/**
 * A variant of Minecraft rabbit entity.
 *
 * @since 1.0
 */
public enum RabbitVariant {
    /**
     * The brown rabbit variant.
     *
     * @since 1.0
     */
    BROWN,
    /**
     * The white rabbit variant.
     *
     * @since 1.0
     */
    WHITE,
    /**
     * The black rabbit variant.
     *
     * @since 1.0
     */
    BLACK,
    /**
     * The white splotched rabbit variant.
     *
     * @since 1.0
     */
    WHITE_SPLOTCHED,
    /**
     * The gold rabbit variant.
     *
     * @since 1.0
     */
    GOLD,
    /**
     * The salt rabbit variant.
     *
     * @since 1.0
     */
    SALT,
    /**
     * The evil rabbit variant.
     *
     * @since 1.0
     */
    EVIL
}